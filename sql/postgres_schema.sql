-- ============================================================================
-- TARGET schema - PostgreSQL 14+
-- Strict: NOT NULLs, CHECKs, FKs, natural-key uniqueness. The migration must
-- hand it clean data or the row is quarantined in healthcare.migration_errors.
-- ============================================================================
DROP SCHEMA IF EXISTS healthcare CASCADE;
CREATE SCHEMA healthcare;
SET search_path TO healthcare;

CREATE TABLE patients (
    patient_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mrn            VARCHAR(20)  NOT NULL UNIQUE,
    first_name     VARCHAR(50)  NOT NULL,
    last_name      VARCHAR(50)  NOT NULL,
    date_of_birth  DATE         NOT NULL CHECK (date_of_birth <= CURRENT_DATE),
    gender         CHAR(1)      NOT NULL DEFAULT 'U' CHECK (gender IN ('M','F','O','U')),
    phone          VARCHAR(12),
    email          VARCHAR(100),
    address_line   VARCHAR(200),
    city           VARCHAR(60),
    state_code     CHAR(2),
    postal_code    VARCHAR(10),
    blood_type     VARCHAR(7)   CHECK (blood_type IN ('A+','A-','B+','B-','AB+','AB-','O+','O-','UNKNOWN')),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT now(),
    migrated_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE appointments (
    appointment_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       INTEGER      NOT NULL REFERENCES patients(patient_id),
    provider_name    VARCHAR(80)  NOT NULL,
    department       VARCHAR(60)  NOT NULL,
    scheduled_at     TIMESTAMP    NOT NULL,
    status           VARCHAR(12)  NOT NULL
                     CHECK (status IN ('SCHEDULED','COMPLETED','CANCELLED','NO_SHOW','UNKNOWN')),
    reason_for_visit TEXT,
    duration_minutes SMALLINT     NOT NULL CHECK (duration_minutes BETWEEN 5 AND 480),
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    migrated_at      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uq_appointment_slot UNIQUE (patient_id, scheduled_at, provider_name)
);
CREATE INDEX idx_appointments_patient ON appointments(patient_id);
CREATE INDEX idx_appointments_scheduled ON appointments(scheduled_at);

CREATE TABLE billing (
    billing_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id         INTEGER       NOT NULL REFERENCES appointments(appointment_id),
    patient_id             INTEGER       NOT NULL REFERENCES patients(patient_id),
    invoice_number         VARCHAR(30)   NOT NULL UNIQUE,
    cpt_code               VARCHAR(10),
    total_amount           NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    insurance_paid         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (insurance_paid >= 0),
    patient_responsibility NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (patient_responsibility >= 0),
    payer_name             VARCHAR(80)   NOT NULL DEFAULT 'Self-Pay',
    status                 VARCHAR(12)   NOT NULL
                           CHECK (status IN ('PAID','PENDING','PARTIAL','DENIED','WRITTEN_OFF','UNKNOWN')),
    invoice_date           DATE          NOT NULL,
    migrated_at            TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT chk_billing_math CHECK (total_amount = insurance_paid + patient_responsibility)
);
CREATE INDEX idx_billing_appointment ON billing(appointment_id);
CREATE INDEX idx_billing_patient ON billing(patient_id);

-- ---------------------------------------------------------------------------
-- Migration bookkeeping
-- ---------------------------------------------------------------------------
-- Every source row that does NOT land in a target table is recorded here with
-- its full raw payload, so nothing disappears silently.
CREATE TABLE migration_errors (
    error_id      BIGSERIAL PRIMARY KEY,
    run_id        UUID         NOT NULL,
    table_name    VARCHAR(30)  NOT NULL,
    source_id     INTEGER,
    error_category VARCHAR(20) NOT NULL
                  CHECK (error_category IN ('REJECTED','MERGED_DUPLICATE','LOAD_FAILURE')),
    error_type    VARCHAR(60)  NOT NULL,
    error_message TEXT,
    raw_record    JSONB,
    logged_at     TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_migration_errors_lookup ON migration_errors(table_name, error_category);

-- One row per table per run: the "control totals" used by reconciliation.
CREATE TABLE migration_audit (
    audit_id             SERIAL PRIMARY KEY,
    run_id               UUID        NOT NULL,
    table_name           VARCHAR(30) NOT NULL,
    source_rows          INTEGER     NOT NULL,   -- rows extracted from MySQL
    duplicates_merged    INTEGER     NOT NULL,   -- removed by de-duplication
    rejected_rows        INTEGER     NOT NULL,   -- failed validation (quarantined)
    expected_load_rows   INTEGER     NOT NULL,   -- rows handed to the loader
    loaded_rows          INTEGER     NOT NULL,   -- rows actually inserted
    load_failures        INTEGER     NOT NULL,   -- rows PostgreSQL refused
    expected_id_checksum CHAR(32)    NOT NULL,   -- md5 of sorted expected PKs
    expected_amount_sum  NUMERIC(14,2),          -- billing only
    started_at           TIMESTAMP   NOT NULL,
    completed_at         TIMESTAMP   NOT NULL,
    UNIQUE (run_id, table_name)
);
